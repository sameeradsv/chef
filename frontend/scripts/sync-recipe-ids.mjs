/**
 * Sync RECIPE_IDS from backend seed data so GitHub Pages static export
 * pre-generates every /recipe/[id] route (meal plan, quick picks, etc.).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const seedPath = join(root, "..", "backend", "data", "seed_recipes.json");
const outPath = join(root, "src", "data", "recipe-ids.ts");

const recipes = JSON.parse(readFileSync(seedPath, "utf8"));
const ids = recipes.map((r) => r.id).filter(Boolean);

if (!ids.length) {
  console.error("sync-recipe-ids: no recipe ids found in", seedPath);
  process.exit(1);
}

const body = `/** Auto-generated by scripts/sync-recipe-ids.mjs — do not edit manually */
export const RECIPE_IDS = ${JSON.stringify(ids, null, 2)} as const;
`;

writeFileSync(outPath, body, "utf8");
console.log(`sync-recipe-ids: wrote ${ids.length} ids → src/data/recipe-ids.ts`);
